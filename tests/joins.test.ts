import type { Register, SessionMessage } from 'claude-code'
import { describe, expect, test } from 'claude-code/testing'

import { buildHandover } from '../src/handover'
import { adoptEarly, backfill, isTypedPrompt, newCockpit, onPrompt, onTurnEnd, onTurnStart, turnSource, unwrapPasted } from '../src/model'
import { historyRows, missionLines } from '../src/panes'
import { heroFace, prettyModel, readingsOf } from '../src/tiles'
import { plain } from '../src/text'
import { at, band, bash, call, command, EN, HOUR, LIMIT_MS, MINUTE, PANE, start, turn, world } from './kit'

const T0 = at(2026, 10, 11, 10)
const VIEW = { now: T0, locale: 'en' as const, days: [], today: '2026-10-11' }
const said = (text: string): SessionMessage => ({ role: 'user', text, toolUses: [] })

/** Another mod that runs a test command of its own when asked: its call is its own, not Claude's. */
const runner: Register = on => {
  on('command.run', { command: 'run-tests' }, async $ => {
    await $.tool.call({ tool: 'Bash', command: 'pnpm test' })
    return {}
  })
}

describe('joining a session, and whose events count', () => {
  test("a tool call another plugin raised is not Claude's check or command", { options: { locale: 'en' }, timeoutMs: LIMIT_MS, plugins: [{ name: 'runner', register: runner }] }, async ($, on) => {
    const w = world(on, { now: T0 })
    w.bash = () => ({ ok: false, stdout: 'Tests  1 failed (1)' })
    await start($, w)
    // Its Bash call takes the mock clock's time: the clock moves while the command runs.
    const ran = $.command.run({ command: 'run-tests', args: '', origin: { kind: 'composer' }, presentation: { isFullscreen: true, columns: 160 } })
    await w.clock.advance(w.bashMs)
    await ran
    await command($, 'handover')
    const text = w.written.at(-1)?.text ?? ''
    expect(text).toContain('Commands run: none.')
    expect(w.toasts.filter(line => line.startsWith('Quack:'))).toEqual([])
    expect(w.notified).toEqual([])
    // Claude's own call of the same command counts.
    await call($, w, bash('pnpm test'))
    await command($, 'handover')
    expect(w.written.at(-1)?.text).toContain('✗ `pnpm test`')
  })

  test("the mission is never Claude Code's compaction summary or a row no person typed; a lost first prompt reads as unknown", () => {
    const summary = 'This session is being continued from a previous conversation that ran out of context. The summary below covers the earlier portion of the conversation.\n\nAnalysis: ...'
    const compacted = backfill(newCockpit(T0, 's'), [said(summary), said('Now make the tests pass')], T0, 2)
    expect(compacted.goal).toBeUndefined()
    expect(compacted.goalLost).toBe(true)
    // A later prompt is not the mission either.
    expect(onPrompt(compacted, { at: T0, text: 'And the lint', isPersonal: true }).goal).toBeUndefined()
    expect(missionLines(readingsOf(compacted, VIEW), 120).map(plain)).toEqual(['MISSION  Unknown: the first prompt is no longer in the transcript (it was compacted).'])
    expect(buildHandover({ c: compacted, now: T0, locale: 'en' })).toContain('Unknown: the first prompt was compacted away before quackpit saw it.')
    const noisy = [
      said('<command-name>/model</command-name>\n<command-message>model</command-message>'),
      said('<local-command-stdout>Set model to opus</local-command-stdout>'),
      said('Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages.'),
      said('[Request interrupted by user]'),
      said('<system-reminder>The user opened a file</system-reminder>'),
      said('Fix the login bug'),
    ]
    expect(backfill(newCockpit(T0, 's'), noisy, T0, 1).goal).toBe('Fix the login bug')
    expect(['/clear', '<task-notification>done</task-notification>', '  ', 'Fix it'].map(isTypedPrompt)).toEqual([false, false, false, true])
    // A transcript of slash commands alone (what /clear leaves) is a fresh start, not a late join.
    const commands = [said('<command-name>/clear</command-name>'), said('<command-name>/quackpit</command-name>')]
    expect(backfill(newCockpit(T0, 's'), commands, T0, 2)).toMatchObject({ turnCount: 0 })
    expect(backfill(newCockpit(T0, 's'), commands, T0, 2).joinedLate).toBeUndefined()
    // Nor is it with the prompt now starting in it, before Claude has answered: that turn is still to count.
    expect(backfill(newCockpit(T0, 's'), [...commands, said('Port the parser')], T0, 3)).toMatchObject({ turnCount: 0, goal: 'Port the parser' })
    const answered = [...commands, said('Port the parser'), { role: 'assistant' as const, text: 'On it.', toolUses: [] }]
    expect(backfill(newCockpit(T0, 's'), answered, T0, 3).joinedLate).toBe(true)
  })

  test("a pasted prompt is the person's words: unwrapped for the mission, the turns table, the handover and the AI ETA, still masked", EN, async ($, on) => {
    const key = 'ghp_abcdefghijklmnopqrstuvwxyz0123456789'
    const brief = `You are improving quackpit, the mod in this folder. The token is ${key}.`
    const pasted = `<pasted_content id="07b3">${brief}</pasted_content id="07b3">`
    expect(isTypedPrompt(pasted)).toBe(true)
    expect(isTypedPrompt('<pasted_content id="1"></pasted_content id="1">')).toBe(false)
    expect(unwrapPasted(`Read this first:\n<pasted_content id="a1">step one</pasted_content>`)).toBe('Read this first:\nstep one')
    expect(turnSource(pasted)).toBeUndefined()
    // What the AI ETA would be sent of the turn: the words, masked, never the markup.
    const live = onTurnStart(newCockpit(T0, 's'), { at: T0, turnId: 't', text: pasted })
    expect(live.turn?.text).toBe('You are improving quackpit, the mod in this folder. The token is ***.')
    expect(live.turn?.prompt).toMatch(/^You are improving quackpit/)
    const w = world(on, { now: T0 })
    await start($, w)
    await turn($, w, { prompt: pasted })
    await turn($, w, { prompt: `<pasted_content id="9f">and keep the duck</pasted_content id="9f"> as it is` })
    // The mission heads the turns view.
    await command($, 'view turns')
    const pane = await $.ui.mount({ plugin: 'quackpit', surface: 'terminal', ...PANE })
    expect(await pane.find({ type: 'Text', text: /^You are improving quackpit, the mod in this folder\. The token is \*\*\*\.$/ })).toBeDefined()
    expect(await pane.find({ type: 'Text', text: /pasted_content/ })).toBeUndefined()
    await pane.unmount()
    await command($, 'handover')
    const handover = w.written.at(-1)?.text ?? ''
    expect(handover).toContain('> and keep the duck as it is')
    expect(handover).not.toContain('pasted_content')
    expect(handover).not.toContain(key)
  })

  test('the session tile names the model as the status line does, read again at start-up (a reload) and at each turn (/model)', EN, async ($, on) => {
    expect(['claude-opus-5-5', 'claude-haiku-4-5-20251001', 'claude-sonnet-4-20250514', 'opus', 'claude-opus-5-5[1m]', 'my-model'].map(prettyModel)).toEqual(['Opus 5.5', 'Haiku 4.5', 'Sonnet 4', 'opus', 'Opus 5.5 1M', 'my-model'])
    // As in the screenshot: a cockpit kept from before with no model, then a reload into it.
    const w = world(on, { now: T0 })
    w.model = undefined
    await start($, w)
    await command($, 'add session')
    const sessionText = async () => {
      const ui = await $.ui.mount({ plugin: 'quackpit', surface: 'terminal', ...band() })
      const found = await ui.find({ type: 'Text', text: /^(Opus 5\.5|Sonnet 4\.5|test|claude.*)$/ })
      await ui.unmount()
      return found?.text
    }
    expect(await sessionText()).toBeUndefined()
    // A response names the model it ran on: that stands in.
    await turn($, w)
    expect(await sessionText()).toBe('test')
    w.model = 'claude-opus-5-5'
    await start($, w)
    expect(await sessionText()).toBe('Opus 5.5')
    w.model = 'claude-sonnet-4-5'
    await turn($, w)
    expect(await sessionText()).toBe('Sonnet 4.5')
  })

  test('a turn no person typed says what started it in the turns table, never its markup, in both languages', () => {
    // As Claude Code delivers them (copied from real transcripts, cut).
    const report = 'Another Claude session sent a message:\n<agent-message from="a15a244c9d581300f">\n[Subagent hand-back] The text below is the final report of a subagent this session delegated to.'
    const bare = '<agent-message from="a2dfe05a50be4097c">\n[Subagent hand-back] The text below is the final report'
    const task = '<task-notification>\n<task-id>a67d69edee884bf89</task-id>\n<status>completed</status>\n<summary>Agent "PR-B evidence search angles" finished</summary>\n</task-notification>'
    const teammate = '<teammate-message teammate_id="team-lead" summary="Review PR5 Task 1">\nYour full instructions are in /tmp/x</teammate-message>'
    const event = '[SYSTEM NOTIFICATION - NOT USER INPUT]\nThis is an automated background-task event, NOT a message from the user.'
    const plugin = 'The savvy-progress plugin sent a message: keep going'
    const texts = [report, bare, task, teammate, event, plugin, '<command-message>review</command-message>\n<command-name>/review</command-name>', 'Fix the parser']
    let c = newCockpit(T0, 's')
    texts.forEach((text, i) => {
      c = onTurnStart(c, { at: T0 + i * MINUTE, turnId: `t${i}`, text })
      c = onTurnEnd(c, { at: T0 + i * MINUTE + 30_000, turnId: `t${i}`, tokens: 10, durationMs: 30_000, isAborted: false })
    })
    const words = (L: 'en' | 'ko') => historyRows(readingsOf(c, { ...VIEW, now: T0 + HOUR, locale: L }), 140).rows.map(row => plain(row.line).split('  ').at(-1))
    expect(words('en')).toEqual([
      'Fix the parser',
      '(/review)',
      '(from the savvy-progress plugin)',
      '(a background event)',
      '(teammate: Review PR5 Task 1)',
      // At most 40 columns: the task's own words give way, never the label around them.
      '(background task: PR-B evidence search…)',
      "(a subagent's report)",
      "(a subagent's report)",
    ])
    expect(words('ko').slice(3)).toEqual(['(백그라운드 이벤트)', '(팀원: Review PR5 Task 1)', '(백그라운드 작업: PR-B evidence search…)', '(서브에이전트 보고)', '(서브에이전트 보고)'])
    // None of them is the person's words: not the mission, not a prompt the handover quotes.
    for (const text of texts.slice(0, -1)) expect(isTypedPrompt(text), text.slice(0, 30)).toBe(false)
    expect(turnSource('Fix the parser')).toBeUndefined()
    expect(turnSource('Another Claude session sent a message:\nhello')).toEqual({ kind: 'peer' })
    // A background command's notice names it in the same way, after two words.
    const shell = '<task-notification>\n<task-id>bp7kc2x7e</task-id>\n<status>completed</status>\n<summary>Background command "Sleep 15 seconds in background" completed (exit code 0)</summary>\n</task-notification>'
    expect(turnSource(shell)).toEqual({ kind: 'task', name: 'Sleep 15 seconds in background' })
  })

  test("a prompt taken in while the session was still being synced (after /clear) is the session's mission", () => {
    // The prompt's event read the state before the sync wrote it: its cockpit has no session id yet.
    const early = onPrompt(newCockpit(T0, ''), { at: T0, text: 'Reply with the single word yes.', isPersonal: true })
    const adopted = adoptEarly(newCockpit(T0, 'session-2'), early)
    expect(adopted).toMatchObject({ sid: 'session-2', goal: 'Reply with the single word yes.' })
    // Where the transcript already gave a mission, it stands.
    const fromTranscript = onPrompt(newCockpit(T0, 'session-2'), { at: T0, text: 'Port the parser', isPersonal: true })
    expect(adoptEarly(fromTranscript, early).goal).toBe('Port the parser')
  })

  test('a session quackpit joined mid-way says when it started watching, not "No turns yet"', EN, async ($, on) => {
    const w = world(on, { now: T0 })
    w.messages = [said('Port the parser'), { role: 'assistant', text: 'On it.', toolUses: [] }]
    await start($, w)
    const hero = heroFace(readingsOf({ ...newCockpit(T0, 's'), joinedLate: true }, VIEW), 60)
    expect(plain(hero.lines[1])).toBe('Watching since 10:00: earlier turns are not counted')
    const ui = await $.ui.mount({ plugin: 'quackpit', surface: 'terminal', ...band() })
    expect(await ui.find({ type: 'Text', text: /^Watching since 10:00/ })).toBeDefined()
    expect(await ui.find({ type: 'Text', text: /No turns yet/ })).toBeUndefined()
    await ui.unmount()
    await command($, '')
    let pane = await $.ui.mount({ plugin: 'quackpit', surface: 'terminal', ...PANE })
    // On top, between turns: since when it is watching.
    expect(await pane.find({ type: 'Text', text: ' · Watching since 10:00: earlier turns are not counted' })).toBeDefined()
    await pane.unmount()
    await command($, 'tab turns')
    pane = await $.ui.mount({ plugin: 'quackpit', surface: 'terminal', ...PANE })
    expect(await pane.find({ type: 'Text', text: 'No turns since 10:00, when quackpit started watching.' })).toBeDefined()
    await pane.unmount()
  })

  test('what a transcript gave back reads "earlier" in Korean too', { options: { locale: 'ko' }, timeoutMs: LIMIT_MS }, async ($, on) => {
    const w = world(on, { now: T0 })
    const failing = 'Exit code 1\n      Tests  1 failed | 2 passed (3)'
    w.messages = [said('업로드 테스트 고치기'), { role: 'assistant', text: '', toolUses: [{ tool_use_id: 'old', tool: 'Bash', input: { command: 'pnpm test' }, isError: true, text: failing, result: failing }] }]
    await start($, w)
    await command($, 'handover')
    expect(w.written.at(-1)?.text).toContain('- ✗ `pnpm test` (이전)')
  })

  test("the session's first measurement counts even when it comes before quackpit has started", EN, async ($, on) => {
    const w = world(on, { now: T0 })
    // Claude Code measures the session as it opens; the plan windows ride on that measurement.
    await $.session.measure({ context: { window: 200_000 }, rateLimits: [{ kind: 'five_hour', percentUsed: 37, resetsAt: new Date(T0 + 2 * 60 * MINUTE).toISOString() }], changed: ['context', 'rateLimits'] })
    await start($, w)
    const ui = await $.ui.mount({ plugin: 'quackpit', surface: 'terminal', ...band() })
    expect(await ui.find({ type: 'Text', text: ' 37%' })).toBeDefined()
    await ui.unmount()
  })
})

